package main

import (
	"bytes"
	"fmt"
	"regexp"
	"sort"
	"strings"
	"time"
)

var rustSafe = regexp.MustCompile(`^[A-Za-z0-9_./<>+@ -]*$`)

// rs quotes a string for Rust. The registry's names are plain ASCII; anything else is a generator error
// rather than an escaping question.
func (e *rustEmitter) rs(s string) string {
	if !rustSafe.MatchString(s) {
		e.err = fmt.Errorf("the string %q has a character the Rust output does not escape", s)
	}
	return `"` + s + `"`
}

type rustEmitter struct {
	w   bytes.Buffer
	err error
}

func (e *rustEmitter) p(format string, a ...any) { fmt.Fprintf(&e.w, format, a...) }

func (e *rustEmitter) strs(s []string) string {
	q := make([]string, len(s))
	for i, v := range s {
		q[i] = e.rs(v)
	}
	return "&[" + strings.Join(q, ", ") + "]"
}

func rustDuration(d time.Duration) string {
	return fmt.Sprintf("Duration::from_secs(%d)", int64(d/time.Second))
}

func rustClass(c string) string {
	return map[string]string{"config": "Class::Config", "secret": "Class::Secret", "durable": "Class::Durable", "temp": "Class::Temp"}[c]
}

func rustScope(s string) string {
	return map[string]string{"boundary": "Scope::Boundary", "boundary+tenant": "Scope::BoundaryTenant"}[s]
}

func emitRust(m *model) ([]byte, error) {
	e := &rustEmitter{}
	e.p("// Code generated by %s; DO NOT EDIT.\n\n", generatedNote)
	e.p("use crate::{Actor, Class, Kind, Scope};\nuse core::time::Duration;\n\n")

	e.p("// Kinds whose lifetime was read from prose or inherited, so that a reviewer sees them:\n//\n")
	for _, n := range m.ttlNotes {
		e.p("//   %s\n", n)
	}
	e.p("\npub(crate) const UID_BASE: u32 = %d;\npub(crate) const UID_BLOCK_STRIDE: u32 = %d;\n\n", uidBase, uidBlockStride)

	e.p("pub(crate) static KINDS: &[Kind] = &[\n")
	for _, k := range m.kinds {
		e.p("    Kind {\n")
		e.p("        name: %s,\n        segment: %s,\n        class: %s,\n        scope: %s,\n        treatment: %s,\n        writer: %s,\n",
			e.rs(k.Name), e.rs(k.Segment), rustClass(k.Class), rustScope(k.Scope), e.rs(k.Treatment), e.rs(k.Writer))
		e.p("        self_scoped: %t,\n        personal: %t,\n        exportable: %t,\n        backed_up: %t,\n        watched: %t,\n",
			k.SelfScoped, k.Personal, k.Exportable, k.BackedUp, k.Watched)
		e.p("        ttl_default: %s,\n        ttl_max: %s,\n        indexes: %s,\n    },\n", rustDuration(k.TTLDefault), rustDuration(k.TTLMax), e.strs(k.Indexes))
	}
	e.p("];\n\n")

	byName := map[string]int{}
	bySeg := map[string]int{}
	for i, k := range m.kinds {
		byName[k.Name] = i
		bySeg[k.Segment] = i
	}
	e.p("pub(crate) static KIND_BY_NAME: &[(&str, usize)] = &[\n")
	for _, k := range sortedKeys(byName) {
		e.p("    (%s, %d),\n", e.rs(k), byName[k])
	}
	e.p("];\n\npub(crate) static KIND_BY_SEGMENT: &[(&str, usize)] = &[\n")
	for _, k := range sortedKeys(bySeg) {
		e.p("    (%s, %d),\n", e.rs(k), bySeg[k])
	}
	e.p("];\n\n")

	rules := make([]ruleKey, 0, len(m.store))
	for k := range m.store {
		rules = append(rules, k)
	}
	sort.Slice(rules, func(i, j int) bool {
		if rules[i].Actor != rules[j].Actor {
			return rules[i].Actor < rules[j].Actor
		}
		return rules[i].Segment < rules[j].Segment
	})
	e.p("// (actor, kind segment, verbs): bit i is the verb at index i of VERBS in lib.rs; bit 7+i marks that verb as\n// self-scoped.\npub(crate) static STORE_RULES: &[(&str, &str, u16)] = &[\n")
	for _, k := range rules {
		e.p("    (%s, %s, 0x%04x), // %s\n", e.rs(k.Actor), e.rs(k.Segment), m.store[k], verbList(m.store[k]))
	}
	e.p("];\n\n")

	krs := make([][2]string, 0, len(m.keys))
	for k := range m.keys {
		krs = append(krs, k)
	}
	sort.Slice(krs, func(i, j int) bool {
		if krs[i][0] != krs[j][0] {
			return krs[i][0] < krs[j][0]
		}
		return krs[i][1] < krs[j][1]
	})
	e.p("// (actor, key purpose, ops): bit i is the op at index i of OPS in lib.rs.\npub(crate) static KEY_RULES: &[(&str, &str, u8)] = &[\n")
	for _, k := range krs {
		e.p("    (%s, %s, 0x%02x),\n", e.rs(k[0]), e.rs(k[1]), m.keys[k])
	}
	e.p("];\n\n")

	e.p("// caller to the sorted callees; the pseudo-callee %q is the audit transport.\npub(crate) static CALLEES: &[(&str, &[&str])] = &[\n", transportCallee)
	for _, k := range sortedKeys(m.callees) {
		e.p("    (%s, %s),\n", e.rs(k), e.strs(m.callees[k]))
	}
	e.p("];\n\n// callee to the sorted callers.\npub(crate) static CALLERS: &[(&str, &[&str])] = &[\n")
	for _, k := range sortedKeys(m.callers) {
		e.p("    (%s, %s),\n", e.rs(k), e.strs(m.callers[k]))
	}
	e.p("];\n\n")

	e.p("// The append-only list of tools/gen/registry/uids.yaml; the index is the ordinal.\npub(crate) static UID_NAMES: &[&str] = %s;\n\n", e.strs(m.uidNames))
	e.p("// (driver user, owning actor), sorted by driver.\npub(crate) static DRIVER_OWNERS: &[(&str, &str)] = &[\n")
	for _, k := range sortedKeys(m.drivers) {
		e.p("    (%s, %s),\n", e.rs(k), e.rs(m.drivers[k]))
	}
	e.p("];\n\n")

	e.p("pub(crate) static ACTORS: &[Actor] = &[\n")
	idx := map[string]int{}
	for i, a := range m.actors {
		idx[a.Name] = i
		e.p("    Actor {\n        name: %s,\n        family: %s,\n        language: %s,\n        holder: %t,\n        ports: %s,\n        calls: %s,\n        egress: %s,\n    },\n",
			e.rs(a.Name), e.rs(a.Family), e.rs(a.Language), a.Holder, e.strs(a.Ports), e.strs(a.Calls), e.strs(a.Egress))
	}
	e.p("];\n\npub(crate) static ACTOR_INDEX: &[(&str, usize)] = &[\n")
	for _, k := range sortedKeys(idx) {
		e.p("    (%s, %d),\n", e.rs(k), idx[k])
	}
	e.p("];\n")

	if e.err != nil {
		return nil, e.err
	}
	return e.w.Bytes(), nil
}
