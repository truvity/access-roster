package main

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"
	"time"
)

const generatedNote = "tools/gen/registry from docs/architecture/actors.yaml, docs/architecture/kinds.yaml, docs/architecture/keys.yaml and tools/gen/registry/uids.yaml"

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func verbList(bits uint16) string {
	var out []string
	for i, v := range verbNames {
		if bits&(1<<i) != 0 {
			s := v
			if bits&(1<<(selfShift+i)) != 0 {
				s += "(self)"
			}
			out = append(out, s)
		}
	}
	return strings.Join(out, " ")
}

func goDuration(d time.Duration) string {
	switch {
	case d == 0:
		return "0"
	case d%(24*time.Hour) == 0:
		return fmt.Sprintf("%d * 24 * time.Hour", d/(24*time.Hour))
	case d%time.Hour == 0:
		return fmt.Sprintf("%d * time.Hour", d/time.Hour)
	case d%time.Minute == 0:
		return fmt.Sprintf("%d * time.Minute", d/time.Minute)
	default:
		return fmt.Sprintf("%d * time.Second", d/time.Second)
	}
}

func goStrings(s []string) string {
	if len(s) == 0 {
		return "nil"
	}
	q := make([]string, len(s))
	for i, v := range s {
		q[i] = strconv.Quote(v)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}

func emitGo(m *model) ([]byte, error) {
	var w bytes.Buffer
	p := func(format string, a ...any) { fmt.Fprintf(&w, format, a...) }

	p("// Code generated by %s; DO NOT EDIT.\n\n", generatedNote)
	p("package registry\n\nimport \"time\"\n\n")

	p("// Kinds whose lifetime was read from prose or inherited, so that a reviewer sees them:\n//\n")
	for _, n := range m.ttlNotes {
		p("//   %s\n", n)
	}
	p("\n")

	p("const (\n\tuidBase        uint32 = %d\n\tuidBlockStride uint32 = %d\n)\n\n", uidBase, uidBlockStride)

	p("var kinds = []Kind{\n")
	for _, k := range m.kinds {
		p("\t{Name: %q, Segment: %q, Class: %q, Scope: %q, Treatment: %q, Writer: %q,\n", k.Name, k.Segment, k.Class, k.Scope, k.Treatment, k.Writer)
		p("\t\tSelfScoped: %t, Personal: %t, Exportable: %t, BackedUp: %t, Watched: %t,\n", k.SelfScoped, k.Personal, k.Exportable, k.BackedUp, k.Watched)
		p("\t\tTTLDefault: %s, TTLMax: %s, Indexes: %s},\n", goDuration(k.TTLDefault), goDuration(k.TTLMax), goStrings(k.Indexes))
	}
	p("}\n\n")

	byName := map[string]int{}
	bySeg := map[string]int{}
	for i, k := range m.kinds {
		byName[k.Name] = i
		bySeg[k.Segment] = i
	}
	p("var kindByName = map[string]int{\n")
	for _, k := range sortedKeys(byName) {
		p("\t%q: %d,\n", k, byName[k])
	}
	p("}\n\nvar kindBySegment = map[string]int{\n")
	for _, k := range sortedKeys(bySeg) {
		p("\t%q: %d,\n", k, bySeg[k])
	}
	p("}\n\n")

	// store rules by actor, then by segment; the number is the bit set of registry.go
	perActor := map[string]map[string]uint16{}
	for k, bits := range m.store {
		if perActor[k.Actor] == nil {
			perActor[k.Actor] = map[string]uint16{}
		}
		perActor[k.Actor][k.Segment] = bits
	}
	p("// storeRules: actor, then kind segment, then the verbs (bit i is verbNames[i]; bit 7+i marks the verb as\n// self-scoped).\nvar storeRules = map[string]map[string]uint16{\n")
	for _, a := range sortedKeys(perActor) {
		p("\t%q: {\n", a)
		for _, s := range sortedKeys(perActor[a]) {
			p("\t\t%q: 0x%04x, // %s\n", s, perActor[a][s], verbList(perActor[a][s]))
		}
		p("\t},\n")
	}
	p("}\n\n")

	perKeyActor := map[string]map[string]uint8{}
	for k, ops := range m.keys {
		if perKeyActor[k[0]] == nil {
			perKeyActor[k[0]] = map[string]uint8{}
		}
		perKeyActor[k[0]][k[1]] = ops
	}
	p("// keyRules: actor, then key purpose, then the ops (bit i is opNames[i]).\nvar keyRules = map[string]map[string]uint8{\n")
	for _, a := range sortedKeys(perKeyActor) {
		p("\t%q: {\n", a)
		for _, s := range sortedKeys(perKeyActor[a]) {
			var ops []string
			for i, o := range opNames {
				if perKeyActor[a][s]&(1<<i) != 0 {
					ops = append(ops, o)
				}
			}
			p("\t\t%q: 0x%02x, // %s\n", s, perKeyActor[a][s], strings.Join(ops, " "))
		}
		p("\t},\n")
	}
	p("}\n\n")

	p("// callees: caller to the sorted callees; the pseudo-callee %q is the audit transport.\nvar callees = map[string][]string{\n", transportCallee)
	for _, k := range sortedKeys(m.callees) {
		p("\t%q: %s,\n", k, goStrings(m.callees[k]))
	}
	p("}\n\n// callers: callee to the sorted callers.\nvar callers = map[string][]string{\n")
	for _, k := range sortedKeys(m.callers) {
		p("\t%q: %s,\n", k, goStrings(m.callers[k]))
	}
	p("}\n\n")

	p("// uidNames: the append-only list of tools/gen/registry/uids.yaml; the index is the ordinal.\nvar uidNames = %s\n\n", goStrings(m.uidNames))
	p("// driverOwners: the user of a driver to the actor that owns it.\nvar driverOwners = map[string]string{\n")
	for _, k := range sortedKeys(m.drivers) {
		p("\t%q: %q,\n", k, m.drivers[k])
	}
	p("}\n\n")

	p("var actors = []Actor{\n")
	for _, a := range m.actors {
		p("\t{Name: %q, Family: %q, Language: %q, Holder: %t, Ports: %s, Calls: %s, Egress: %s},\n",
			a.Name, a.Family, a.Language, a.Holder, goStrings(a.Ports), goStrings(a.Calls), goStrings(a.Egress))
	}
	p("}\n\nvar actorIndex = map[string]int{\n")
	for i, a := range m.actors {
		p("\t%q: %d,\n", a.Name, i)
	}
	p("}\n")

	out, err := format.Source(w.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting the Go output: %w", err)
	}
	return out, nil
}
