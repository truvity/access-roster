package main

import (
	"fmt"
	"sort"

	"github.com/truvity/sluis/v2/kits/go/audit"
)

// The fixed inputs of the example records: the same as the shape of kits/conformance/audit/record-vectors.json, so
// that one reader reads both files.
const (
	vecBoundary    = "dev"
	vecRelease     = "0.0.0-test"
	vecUID         = "01950000-0000-7000-8000-000000000001"
	vecTimeMS      = 1793750400000
	vecCorrelation = "req-7f3a_01"
	vecPseudonym   = "p1.202611.AAAAAAAAAAAAAAAAAAAAAA"
)

type vecAction struct {
	Name         string `json:"name"`
	ClassUID     int    `json:"class_uid"`
	ActivityID   int    `json:"activity_id"`
	ActivityName string `json:"activity_name,omitempty"`
}

type vecSubject struct {
	Tenant string `json:"tenant"`
	Kind   string `json:"kind"`
	Value  string `json:"value"`
}

type vecPolicy struct {
	DecisionID string   `json:"decision_id"`
	Digest     string   `json:"digest,omitempty"`
	PolicyIDs  []string `json:"policy_ids,omitempty"`
	Decision   int      `json:"decision,omitempty"`
}

type vecEntity struct {
	Type    string `json:"type"`
	Name    string `json:"name,omitempty"`
	UID     string `json:"uid,omitempty"`
	Version string `json:"version,omitempty"`
}

type vecEvent struct {
	Action     vecAction      `json:"action"`
	Subject    *vecSubject    `json:"subject,omitempty"`
	Status     int            `json:"status"`
	StatusCode string         `json:"status_code,omitempty"`
	Tenant     string         `json:"tenant,omitempty"`
	Sluis      map[string]any `json:"sluis,omitempty"`
	Policy     *vecPolicy     `json:"policy,omitempty"`
	Entity     *vecEntity     `json:"entity,omitempty"`
}

type vecCase struct {
	Name        string   `json:"name"`
	Actor       string   `json:"actor"`
	Boundary    string   `json:"boundary"`
	Release     string   `json:"release"`
	UID         string   `json:"uid"`
	TimeMS      int64    `json:"time_ms"`
	Correlation string   `json:"correlation"`
	Pseudonym   string   `json:"pseudonym,omitempty"`
	Event       vecEvent `json:"event"`
	Expected    string   `json:"expected"`
}

type vecFile struct {
	Comment string    `json:"comment"`
	Cases   []vecCase `json:"cases"`
}

// normal turns what the YAML decoder returns into the types of audit.Event.Sluis: int64, []string, nested maps.
func normal(v any) (any, error) {
	switch x := v.(type) {
	case string, bool:
		return x, nil
	case int:
		return int64(x), nil
	case []any:
		out := []string{}
		for _, e := range x {
			s, ok := e.(string)
			if !ok {
				return nil, fmt.Errorf("a list of something other than strings")
			}
			out = append(out, s)
		}
		return out, nil
	case map[string]any:
		out := map[string]any{}
		for k, e := range x {
			n, err := normal(e)
			if err != nil {
				return nil, err
			}
			out[k] = n
		}
		return out, nil
	}
	return nil, fmt.Errorf("a value of type %T", v)
}

func buildVectors(t *tableFile) ([]byte, error) {
	f := vecFile{Comment: "One example record for each action of the table (docs/architecture/audit-actions.yaml), built by the Go library from resolved inputs. Generated by tools/gen/audit; do not edit. Go and Rust must build the same bytes, and every record validates against kits/conformance/audit/schema (REQ-AUDIT-002, REQ-AUDIT-101)."}
	for _, a := range t.Actions {
		ex := a.Example
		ac := a.activities()[0]
		if ex.Activity != nil {
			ac = *ex.Activity
		}
		status := 1
		switch {
		case ex.Status == "failure":
			status = 2
		case ex.Status == "" && len(a.Outcomes) == 1 && a.Outcomes[0] == "failure":
			status = 2
		}
		ev := vecEvent{
			Action: vecAction{Name: a.Name, ClassUID: a.Class, ActivityID: ac.ID, ActivityName: ac.Name},
			Status: status, StatusCode: ex.StatusCode, Tenant: ex.Tenant,
		}
		if status == 2 && ev.StatusCode == "" {
			return nil, fmt.Errorf("action %s: the example of a failure has a status_code", a.Name)
		}
		if len(ex.Sluis) > 0 {
			n, err := normal(ex.Sluis)
			if err != nil {
				return nil, fmt.Errorf("action %s: example: %w", a.Name, err)
			}
			ev.Sluis = n.(map[string]any)
		}
		pseudonym := ""
		if ex.Subject {
			tenant := ex.Tenant
			if tenant == "" {
				tenant = "acme"
			}
			ev.Subject = &vecSubject{Tenant: tenant, Kind: "person", Value: "person-1"}
			pseudonym = vecPseudonym
		}
		if p := ex.Policy; p != nil {
			ev.Policy = &vecPolicy{DecisionID: p.DecisionID, Digest: p.Digest, PolicyIDs: p.PolicyIDs, Decision: map[string]int{"": 0, "allowed": 1, "denied": 2}[p.Decision]}
		}
		ae := audit.Event{
			Action: audit.Action{Name: a.Name, ClassUID: a.Class, ActivityID: ac.ID, ActivityName: ac.Name},
			Status: audit.Status(status), StatusCode: ex.StatusCode, Tenant: ex.Tenant, Sluis: ev.Sluis,
		}
		if x := ex.Entity; x != nil {
			ev.Entity = &vecEntity{Type: a.Entity.Type, Name: x.Name, UID: x.UID, Version: x.Version}
			ae.Entity = &audit.Entity{Type: a.Entity.Type, Name: x.Name, UID: x.UID, Version: x.Version}
		}
		if ev.Subject != nil {
			ae.Subject = &audit.Subject{Tenant: ev.Subject.Tenant, Kind: ev.Subject.Kind, Value: ev.Subject.Value}
		}
		if p := ev.Policy; p != nil {
			ae.Policy = &audit.PolicyRef{DecisionID: p.DecisionID, Digest: p.Digest, PolicyIDs: p.PolicyIDs, Decision: audit.Decision(p.Decision)}
		}
		rec, err := audit.BuildRecord(a.Actor, vecBoundary, vecRelease, vecUID, vecTimeMS, vecCorrelation, pseudonym, ae)
		if err != nil {
			return nil, fmt.Errorf("action %s: %w", a.Name, err)
		}
		f.Cases = append(f.Cases, vecCase{
			Name: a.Name, Actor: a.Actor, Boundary: vecBoundary, Release: vecRelease, UID: vecUID, TimeMS: vecTimeMS,
			Correlation: vecCorrelation, Pseudonym: pseudonym, Event: ev, Expected: string(rec),
		})
	}
	sort.SliceStable(f.Cases, func(i, j int) bool { return f.Cases[i].Name < f.Cases[j].Name })
	return marshal(f, true)
}
