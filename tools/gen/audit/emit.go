package main

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
)

const header = "Generated from docs/architecture/audit-actions.yaml by tools/gen/audit (`just audit-gen`). Do not edit."

func outcomeIDs(a action) []int {
	var out []int
	for _, o := range a.Outcomes {
		if o == "success" {
			out = append(out, 1)
		}
	}
	for _, o := range a.Outcomes {
		if o == "failure" {
			out = append(out, 2)
		}
	}
	return out
}

func emitGo(t *tableFile, texts map[string]string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/gen/audit. DO NOT EDIT.\n// %s\n\npackage audit\n\n", header)
	fmt.Fprintf(&b, "// sluisRows are the actions of sluis (%d).\nvar sluisRows = []Row{\n", len(t.Actions))
	for _, a := range t.Actions {
		var acts, outs []string
		for _, ac := range a.activities() {
			acts = append(acts, fmt.Sprintf("{ID: %d, Name: %q}", ac.ID, ac.Name))
		}
		for _, o := range outcomeIDs(a) {
			outs = append(outs, map[int]string{1: "StatusSuccess", 2: "StatusFailure"}[o])
		}
		fmt.Fprintf(&b, "\t{Name: %q, Actor: %q, Class: %d, Activities: []Activity{%s}, Outcomes: []Status{%s}},\n",
			a.Name, a.Actor, a.Class, strings.Join(acts, ", "), strings.Join(outs, ", "))
	}
	b.WriteString("}\n\n// sluisSchemas are the JSON Schema documents of the records, by file name.\nvar sluisSchemas = map[string]string{\n")
	for _, n := range sortedNames(texts) {
		fmt.Fprintf(&b, "\t%q: %s,\n", n, quote(strings.TrimSpace(texts[n])))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func emitRust(t *tableFile, texts map[string]string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// @generated by tools/gen/audit. DO NOT EDIT.\n// %s\n\n", header)
	b.WriteString("use crate::table::{Activity, Row};\n\n")
	fmt.Fprintf(&b, "/// The actions of sluis (%d).\npub(crate) static ROWS: &[Row] = &[\n", len(t.Actions))
	for _, a := range t.Actions {
		var acts []string
		for _, ac := range a.activities() {
			acts = append(acts, fmt.Sprintf("Activity { id: %d, name: %q }", ac.ID, ac.Name))
		}
		var outs []string
		for _, o := range outcomeIDs(a) {
			outs = append(outs, fmt.Sprint(o))
		}
		fmt.Fprintf(&b, "    Row {\n        name: %q,\n        actor: %q,\n        class: %d,\n        activities: &[%s],\n        outcomes: &[%s],\n    },\n",
			a.Name, a.Actor, a.Class, strings.Join(acts, ", "), strings.Join(outs, ", "))
	}
	b.WriteString("];\n\n/// The JSON Schema documents of the records, by file name.\npub(crate) static SCHEMAS: &[(&str, &str)] = &[\n")
	for _, n := range sortedNames(texts) {
		if strings.Contains(texts[n], `"####`) {
			return nil, fmt.Errorf("%s holds a raw string delimiter", n)
		}
		fmt.Fprintf(&b, "    (\n        %q,\n        r####\"%s\"####,\n    ),\n", n, strings.TrimSpace(texts[n]))
	}
	b.WriteString("];\n")
	return b.Bytes(), nil
}
