package main

import (
	"fmt"
	"strings"
)

// dockerfileDir holds the generated Dockerfiles, one per image.
const dockerfileDir = "deploy/release"

// imagesFile is the list of the images of the release, which tools/release reads: what to build, from what, with which labels.
const imagesFile = "deploy/release/images.yaml"

// vendorNotice is the licence text of the vendor program, shipped in its image (a committed copy of the upstream file at the tag).
const vendorNotice = "deploy/vendor/rqlite.LICENSE"

// staticBase is the base of every executable that is static: distroless static, the nonroot variant, pinned by digest
// (MEASURED 2026-11-04 with `docker inspect` on gcr.io/distroless/static-debian12:nonroot). deploy/local/Dockerfile carries
// the same pin for the images the local installation builds from source; a test holds them together.
const staticBase = "gcr.io/distroless/static-debian12:nonroot@sha256:afa5c872c891853ca7fcf1f12c3edb23f7eeef36189728842dd51042ff57f7ab"

// glibcBase is the base of the engine, which is linked to glibc and, in the debug variant, has a busybox that answers its
// health check (MEASURED 2026-11-04, gcr.io/distroless/base-debian12:debug-nonroot).
const glibcBase = "gcr.io/distroless/base-debian12:debug-nonroot@sha256:9162795c8ec16d4f83921e4c173d07ce366a5d6eef9c461e707dbef4f81146b9"

// Vendor is a program of someone else that an installation runs beside sluis: it is published as an image of its own, at
// /usr/libexec/sluis/vendor/<name>, and not built from the tree.
type Vendor struct {
	Name     string // the image is vendor-<Name>
	Bin      string // the file name
	Version  string // the upstream version
	Base     string
	SrcDir   string // below the repository root, with {arch} for the architecture: where `just rqlite-fetch` puts it
	Describe string
}

// ImageName is the name of the image below the registry.
func (v Vendor) ImageName() string { return "vendor-" + v.Name }

var vendorRqlite = Vendor{
	Name:     "rqlite",
	Bin:      "rqlited",
	Version:  "10.6.6",
	Base:     glibcBase,
	SrcDir:   ".cache/rqlite/linux-{arch}",
	Describe: "rqlite, the engine of the store driver on the local installation",
}

// installPath is where the vendor program sits in its image.
func (v Vendor) installPath() string { return "/usr/libexec/sluis/vendor/" + v.Bin }

// noticePath is where its licence sits in the image.
func (v Vendor) noticePath() string { return "/usr/share/doc/sluis/" + v.ImageName() + "/LICENSE" }

func renderVendorDockerfile(v Vendor) string {
	return dockerfileHeader(v.ImageName()) + fmt.Sprintf(`FROM %s
ARG TARGETPLATFORM
COPY --chmod=0555 ${TARGETPLATFORM}/%s %s
COPY --chmod=0444 LICENSE %s
ENTRYPOINT ["%s"]
`, v.Base, v.Bin, v.installPath(), v.noticePath(), v.installPath())
}

func dockerfileHeader(name string) string {
	return "# Generated by tools/gen/release for the image " + name + ". Do not edit: run `just release-gen`.\n" +
		"# tools/release publish puts the executable of each platform in the build context at <os>/<arch>/<name>.\n"
}

// RenderDockerfile is the Dockerfile of the image of one executable: the static base, the executable at the install path of
// the package, byte for byte, and nothing else (ADR 0013, "Images"). The user is the base's nonroot user; the Compose file
// and the chart set the uid of each process.
func RenderDockerfile(e Exec) string {
	return dockerfileHeader(e.Name()) + fmt.Sprintf(`FROM %s
ARG TARGETPLATFORM
COPY --chmod=0555 ${TARGETPLATFORM}/%s %s
ENTRYPOINT ["%s"]
`, staticBase, e.Bin, e.InstallPath(), e.InstallPath())
}

// RenderImages is deploy/release/images.yaml: every image of the release, what it holds and how it is labelled. tools/release
// publishes from it and checks the registry against it.
func RenderImages(execs []Exec) string {
	var b strings.Builder
	b.WriteString("# Generated by tools/gen/release. Do not edit: run `just release-gen`.\n")
	b.WriteString("# The images of the release, one per actor and driver and one for the engine of the local installation (ADR 0013).\n")
	b.WriteString("# source archive: the executable is taken from the archive `package` of each architecture. source vendor: it is\n")
	b.WriteString("# `vendor_path` (a program of someone else, verified by `just rqlite-fetch`), with its licence text `notice_file`.\n")
	b.WriteString("# layers: how many layers the build adds to the base; each holds the files `files` names, and nothing else.\n")
	b.WriteString("images:\n")
	for _, e := range execs {
		if !e.HasImage() || e.Native() {
			continue
		}
		fmt.Fprintf(&b, "  - name: %s\n    dockerfile: %s/Dockerfile.%s\n    title: %q\n    package: %s\n    source: archive\n    bin: %s\n    licence: MIT\n    layers: 1\n    files: [%s]\n",
			e.Name(), dockerfileDir, e.Name(), "sluis "+e.Kind()+" "+strings.TrimPrefix(e.Name(), e.Kind()+"-"), e.ArchiveName(), e.Bin, e.InstallPath())
	}
	v := vendorRqlite
	fmt.Fprintf(&b, "  - name: %s\n    dockerfile: %s/Dockerfile.%s\n    title: %q\n    package: %q\n    source: vendor\n    bin: %s\n    vendor_path: %q\n    notice_file: %s\n    licence: MIT\n    layers: 2\n    files: [%s, %s]\n",
		v.ImageName(), dockerfileDir, v.ImageName(), v.Describe, "upstream rqlite v"+v.Version, v.Bin, v.SrcDir+"/"+v.Bin, vendorNotice, v.installPath(), v.noticePath())
	return b.String()
}
