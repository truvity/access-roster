// Shared helpers of the page generators in tools/checks/ (glossary-page, kinds-page, rules-page,
// keys-page). Each generator renders one block of a page from a registry; the block sits between
// two markers, `just <name>-write` rewrites it and the check fails while it is stale. The page's
// own text above and below the block is written by hand and is not touched.
//
// Needs the `yaml` package of site/ (`just site-install`). No other dependency.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { reporter, repoRoot } from './lib.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const { parse } = createRequire(join(here, '..', '..', 'site', 'package.json'))('yaml');

export const END = '<!-- END GENERATED -->';
export const beginMarker = (script, source) => `<!-- BEGIN GENERATED by tools/checks/${script} from ${source}; do not edit -->`;

// The id Starlight gives a heading: lower case, punctuation dropped, spaces to hyphens.
export const slug = (text) => text.toLowerCase().replace(/`/g, '').replace(/[^\p{L}\p{N}\- _]/gu, '').replace(/ /g, '-');
// PascalCase to kebab-case: DataKeyWrap -> data-key-wrap.
export const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2').toLowerCase();

// Text for a table cell or a line of prose: `<` outside a code span would start an HTML tag, and a
// pipe would end the cell. A code span keeps its text; only its pipes are escaped.
export function md(text) {
  return String(text ?? '').split(/(`[^`]*`)/).map((part, i) => (i % 2
    ? part.replace(/\|/g, '\\|')
    : part.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/\|/g, '\\|'))).join('').replace(/\s*\n\s*/g, ' ');
}
export const code = (s) => `\`${s}\``;
export const list = (xs, none = 'none', sep = ', ') => (xs.length ? xs.join(sep) : none);
export const table = (head, rows) => [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)];
export const anchor = (id) => `<a id="${id}"></a>`;

// The setup of one generator: the root, the flags, the reporter and the loaders.
export function generator(name, script, { source, page, recipe }) {
  const root = repoRoot();
  const write = process.argv.includes('--write');
  const { error, errors, finish } = reporter(name);
  const read = (rel) => readFileSync(join(root, rel), 'utf8');
  const load = (rel) => {
    if (!existsSync(join(root, rel))) { error(`${rel} is missing`); return null; }
    try { return parse(read(rel)); } catch (e) { error(`${rel}: not valid YAML: ${e.message}`); return null; }
  };
  const begin = beginMarker(script, source);

  // The decision records, for the links on the page: a link to a record or to one of its headings
  // that does not exist is an error, so a generated page never carries a dead link.
  const dir = join(root, 'docs', 'decisions');
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => /^[0-9]{4}-.*\.md$/.test(f) && !f.startsWith('0000')) : [];
  const records = new Map(files.map((f) => {
    const text = readFileSync(join(dir, f), 'utf8');
    return [f.slice(0, 4), { slug: f.replace(/\.md$/, ''), headings: new Set([...text.matchAll(/^#{2,6} +(.+?) *$/gm)].map((m) => slug(m[1]))) }];
  }));
  const adrHref = (num, heading) => {
    const r = records.get(num);
    if (!r) { error(`${page}: the link to ADR ${num} has no record in docs/decisions/`); return `/decisions/${num}/`; }
    if (heading && !r.headings.has(heading)) error(`${page}: ADR ${num} (${r.slug}) has no heading #${heading}`);
    return `/decisions/${r.slug}/${heading ? `#${heading}` : ''}`;
  };
  const adr = (num, heading, label = `ADR ${num}`) => `[${label}](${adrHref(num, heading)})`;
  // A cited decision as `NNNN-slug` or `NNNN-slug#heading` (the glossary's form).
  const adrRef = (ref) => {
    const m = /^([0-9]{4})-([a-z0-9-]+)(?:#(.+))?$/.exec(ref);
    if (!m) { error(`${page}: ${ref}: not a decision record reference`); return ref; }
    const r = records.get(m[1]);
    if (!r) { error(`${page}: ${ref}: there is no record ${m[1]} in docs/decisions/`); return `ADR ${m[1]}`; }
    if (r.slug !== `${m[1]}-${m[2]}`) error(`${page}: ${ref}: the record ${m[1]} is ${r.slug}`);
    if (m[3] && !r.headings.has(m[3])) error(`${page}: ${ref}: ${r.slug} has no heading #${m[3]}`);
    return `[ADR ${m[1]}](/decisions/${r.slug}/${m[3] ? `#${m[3]}` : ''})`;
  };

  // Ids on the page must be unique: the headings of the block and the anchors it places.
  const ids = new Map();
  const claim = (id, what) => {
    if (ids.has(id)) error(`${page}: the id #${id} is used twice (${ids.get(id)} and ${what})`);
    else ids.set(id, what);
  };
  const heading = (level, text) => { claim(slug(text), `the heading "${text}"`); return `${'#'.repeat(level)} ${text}`; };

  // Compare the rendered block with the page, or rewrite it. `render()` returns the block's lines
  // between the markers; `intro` is the text of the page when it has to be created (never used here).
  function sync(render, checked, what) {
    if (!errors.length) {
      let want;
      try { want = [begin, '', ...render(), '', END].join('\n'); } catch (e) { error(`${page}: cannot render: ${e.message}`); }
      if (!errors.length) {
        if (!existsSync(join(root, page))) error(`${page} is missing`);
        else {
          const text = read(page);
          const b = text.indexOf(begin);
          const e = text.indexOf(END);
          if (b < 0 || e < b) error(`${page}: the generated block markers are missing (expected ${begin})`);
          else if (text.slice(b, e + END.length) !== want) {
            if (write) {
              writeFileSync(join(root, page), text.slice(0, b) + want + text.slice(e + END.length));
              console.log(`${name}: rewrote the generated block of ${page}`);
            } else error(`${page}: the generated block is stale; run \`just ${recipe}\``);
          }
        }
      }
    }
    finish(checked, what);
  }
  return { root, error, errors, finish, load, read, adr, adrHref, adrRef, claim, heading, sync, write };
}
