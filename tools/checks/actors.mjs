#!/usr/bin/env node
// The actor registry, docs/architecture/actors.yaml, against everything else that names an actor.
//
//   - the registry itself: one row per actor, closed fields, the four families, who is a credential
//     holder (store, exporter, key and the audit pieces; never a work actor), the ports (a work actor
//     has exactly a data, a keys and an audit-emit port and the ports of its job; a port that is not
//     shared belongs to one family; store has its four ports downward), the calls (to actors, never
//     to store or key, which the ports reach), the egress classes, the key purposes' ops, languages,
//     rules, placements, record numbers, requirement areas, standards, and the label `actor:<name>`;
//   - the explorer, site/src/data/explorer/architecture.yaml: every role it draws is an actor of the
//     registry and its node agent is the platform piece of the registry;
//   - the decision records: each record an actor lists exists (an error), and names the actor, an
//     instance name `<name>@<...>` in a record is an actor or a declared non-actor, and the language
//     and rule agree with the per-actor table of the language record (warnings: the records are
//     rewritten wave by wave; `--strict-adrs` makes them errors);
//   - the requirement records: every name in a record's optional `actors:` is an actor or a platform
//     piece, and the record's area is one of that actor's requirement areas;
//   - the generated tables on docs/reference/actors.md are current (`--write` rewrites them).
//
// The key purposes an actor lists are checked against docs/architecture/keys.yaml, and the kinds an
// actor writes and reads against docs/architecture/kinds.yaml, by tools/checks/registries.mjs.
//
// Needs the `yaml` package of site/ (`just site-install`).
//
// usage: tools/checks/actors.mjs [--write] [--strict-adrs] [repo-root]
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { reporter, repoRoot } from './lib.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const { parse } = createRequire(join(here, '..', '..', 'site', 'package.json'))('yaml');

const root = repoRoot();
const write = process.argv.includes('--write');
const strictAdrs = process.argv.includes('--strict-adrs');
const { error, errors, finish } = reporter('check-actors');
const warnings = [];
const adrProblem = (m) => (strictAdrs ? error(m) : warnings.push(m));

const REGISTRY = 'docs/architecture/actors.yaml';
const EXPLORER = 'site/src/data/explorer/architecture.yaml';
const PAGE = 'docs/reference/actors.md';
const BEGIN = '<!-- BEGIN GENERATED by tools/checks/actors.mjs from docs/architecture/actors.yaml; do not edit -->';
const END = '<!-- END GENERATED -->';

const FAMILIES = ['work', 'data', 'keys', 'audit'];
const LANGUAGES = ['Go', 'Rust'];
const SCOPES = ['per-boundary', 'front', 'per-node', 'per-tenant', 'beside-sluis'];
const INSTANCES = ['any', 'exactly-1'];
const RUNTIMES = ['bare-metal', 'serverless', 'kubernetes'];
const OPS = ['seal', 'open', 'sign', 'mac', 'public-key', 'wrap', 'unwrap'];
const CONTRACTS = ['Upstream', 'FactsSource', 'CredentialMinter', 'Provisioner', 'Notifier'];
const WORK_PORTS = ['data', 'keys', 'audit-emit'];
const STORE_PORTS = ['config-source', 'secret-source', 'durable', 'temp'];
const TOP = ['schema', 'ports', 'egress_classes', 'actors', 'platform', 'not_actors'];
const FIELDS = ['name', 'family', 'holder', 'holds', 'purpose', 'aka', 'contracts', 'language', 'language_rule', 'language_row', 'language_note',
  'placement', 'ports', 'calls', 'egress', 'key_purposes', 'adrs', 'requirement_areas', 'standards', 'label', 'issues'];
const PLATFORM_FIELDS = ['name', 'purpose', 'language', 'language_rule', 'language_note', 'placement', 'binary', 'ports', 'calls', 'egress',
  'key_purposes', 'adrs', 'requirement_areas', 'standards', 'label', 'issues'];
const REQUIRED = ['name', 'family', 'holder', 'purpose', 'language', 'language_rule', 'placement', 'ports', 'calls', 'egress', 'key_purposes',
  'adrs', 'requirement_areas', 'standards', 'label', 'issues'];
const PLATFORM_REQUIRED = PLATFORM_FIELDS.filter((f) => !['language_note'].includes(f));
const MACRO = 'adapter-<vendor>';

const read = (rel) => readFileSync(join(root, rel), 'utf8');
const load = (rel) => {
  if (!existsSync(join(root, rel))) return null;
  try { return parse(read(rel)); } catch (e) { error(`${rel}: not valid YAML: ${e.message}`); return null; }
};
const isStrList = (v) => Array.isArray(v) && v.every((x) => typeof x === 'string');
const isObj = (v) => v && typeof v === 'object' && !Array.isArray(v);
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// ---- the registry
const reg = load(REGISTRY);
if (!reg) {
  error(`${REGISTRY} is missing`);
  finish(0, 'actors');
}
if (reg.schema !== 1) error(`${REGISTRY}: schema must be 1`);
for (const k of Object.keys(reg)) if (!TOP.includes(k)) error(`${REGISTRY}: unknown top-level key ${k}`);
const actors = Array.isArray(reg.actors) ? reg.actors : [];
const platform = Array.isArray(reg.platform) ? reg.platform : [];
const portDefs = isObj(reg.ports) ? reg.ports : {};
const egressDefs = isObj(reg.egress_classes) ? reg.egress_classes : {};
for (const [n, p] of Object.entries(portDefs)) {
  if (!isObj(p) || typeof p.description !== 'string') error(`${REGISTRY}: ports.${n}: needs a description`);
  else if (p.shared === true ? 'family' in p : !FAMILIES.includes(p.family)) error(`${REGISTRY}: ports.${n}: a port is shared (shared: true) or belongs to one family (family: ${FAMILIES.join(' | ')})`);
}
for (const [n, d] of Object.entries(egressDefs)) if (typeof d !== 'string') error(`${REGISTRY}: egress_classes.${n}: needs a description`);

const byName = new Map();
const everyone = new Map(); // actors and platform pieces
const usedEgress = new Set();
const isAdapter = (a) => /^adapter-[a-z][a-z0-9-]*$/.test(a.name);

function common(a, at, fields, required) {
  for (const k of Object.keys(a)) if (!fields.includes(k)) error(`${at}: unknown field ${k}`);
  for (const k of required) if (!(k in a)) error(`${at}: missing ${k}`);
  if (typeof a.name !== 'string' || !/^[a-z][a-z0-9-]*$/.test(a.name)) { error(`${at}: name must be lower-case kebab-case`); return false; }
  if (everyone.has(a.name)) error(`${at}: the name is used twice`);
  everyone.set(a.name, a);
  if (typeof a.purpose !== 'string' || !/^[A-Z"`].{10,300}\.$/.test(a.purpose)) error(`${at}: purpose must be one sentence ending in a period`);
  if (!LANGUAGES.includes(a.language)) error(`${at}: language must be one of ${LANGUAGES.join(', ')}`);
  if (typeof a.language_rule !== 'string' || !/^R(?:[1-9]|1[01])$/.test(a.language_rule)) error(`${at}: language_rule must be R1 to R11 (the language record)`);
  const p = a.placement ?? {};
  if (!SCOPES.includes(p.scope)) error(`${at}: placement.scope must be one of ${SCOPES.join(', ')}`);
  if (!INSTANCES.includes(p.instances)) error(`${at}: placement.instances must be one of ${INSTANCES.join(', ')}`);
  if (!isStrList(p.runtimes) || !p.runtimes.length || p.runtimes.some((r) => !RUNTIMES.includes(r))) error(`${at}: placement.runtimes must list runtimes of ${RUNTIMES.join(', ')}`);
  for (const k of Object.keys(p)) if (!['scope', 'instances', 'runtimes', 'note'].includes(k)) error(`${at}: unknown placement field ${k}`);
  if (!isStrList(a.ports) || new Set(a.ports).size !== a.ports.length) error(`${at}: ports must be a list of port names, each once`);
  for (const port of isStrList(a.ports) ? a.ports : []) if (!(port in portDefs)) error(`${at}: port ${port} is not declared under ports`);
  if (!isStrList(a.egress)) error(`${at}: egress must be a list of egress classes ([] for none)`);
  for (const e of isStrList(a.egress) ? a.egress : []) {
    usedEgress.add(e);
    if (!(e in egressDefs)) error(`${at}: egress class ${e} is not declared under egress_classes`);
  }
  if (!Array.isArray(a.key_purposes)) error(`${at}: key_purposes must be a list`);
  for (const [j, k] of (Array.isArray(a.key_purposes) ? a.key_purposes : []).entries()) {
    if (typeof k?.purpose !== 'string') error(`${at}: key_purposes[${j}] needs a purpose`);
    if (!isStrList(k?.ops) || !k.ops.length || k.ops.some((o) => !OPS.includes(o))) error(`${at}: key_purposes[${j}].ops must list ${OPS.join(', ')}`);
    for (const f of Object.keys(k ?? {})) if (!['purpose', 'ops'].includes(f)) error(`${at}: key_purposes[${j}]: unknown field ${f}`);
  }
  if (!isStrList(a.adrs) || a.adrs.some((n) => !/^[0-9]{4}$/.test(n))) error(`${at}: adrs must list four-digit record numbers, quoted`);
  if (!isStrList(a.requirement_areas)) error(`${at}: requirement_areas must be a list of area codes`);
  if (!isStrList(a.standards)) error(`${at}: standards must be a list of ids`);
  if (a.label !== `actor:${a.name}`) error(`${at}: label must be actor:${a.name}`);
  if (!Array.isArray(a.issues) || a.issues.some((n) => !Number.isInteger(n) || n < 1) || new Set(a.issues).size !== a.issues.length) error(`${at}: issues must be unique issue numbers`);
  return true;
}

for (const [i, a] of actors.entries()) {
  const at = `${REGISTRY}: actors[${i}]${a?.name ? ` (${a.name})` : ''}`;
  if (!isObj(a)) { error(`${at}: not an object`); continue; }
  if (!common(a, at, FIELDS, REQUIRED)) continue;
  byName.set(a.name, a);
  if (!FAMILIES.includes(a.family)) { error(`${at}: family must be one of ${FAMILIES.join(', ')}`); continue; }
  if (typeof a.holder !== 'boolean') error(`${at}: holder must be true or false`);
  if ('aka' in a && !isStrList(a.aka)) error(`${at}: aka must be a list of strings`);
  if (a.family === 'work' && a.holder) error(`${at}: a work actor holds no credential at rest`);
  if (a.family !== 'work' && a.holder === false) error(`${at}: store, exporter, key and the audit pieces hold a credential, so holder is true`);
  if (a.holder === true && !(isStrList(a.holds) && a.holds.length)) error(`${at}: a holder says what it holds (holds)`);
  if (a.holder !== true && 'holds' in a) error(`${at}: only a holder has holds`);
  if (isAdapter(a)) {
    if (a.family !== 'work') error(`${at}: an adapter is a work actor`);
    if (!isStrList(a.contracts) || !a.contracts.length || a.contracts.some((c) => !CONTRACTS.includes(c))) error(`${at}: an adapter lists the contracts it implements, of ${CONTRACTS.join(', ')}`);
  } else if ('contracts' in a) error(`${at}: only an adapter has contracts`);
  if (a.family === 'audit' && !['writer', 'witness', 'indexer', 'reader'].includes(a.name)) error(`${at}: the audit family is writer, witness, indexer and reader`);
  // ports
  const ports = isStrList(a.ports) ? a.ports : [];
  for (const port of ports) {
    const def = portDefs[port];
    if (def && def.shared !== true && def.family !== a.family) error(`${at}: port ${port} belongs to the ${def.family} family; a port is never shared between families`);
  }
  if (a.family === 'work') {
    for (const port of WORK_PORTS) if (!ports.includes(port)) error(`${at}: a work actor has a ${port} port`);
    if (ports.includes('listener') && a.name !== 'entry') error(`${at}: only entry has a listener`);
    if (a.name === 'entry' && !ports.includes('listener')) error(`${at}: entry has the listener`);
  }
  if (a.name === 'store') {
    const down = ports.filter((p) => STORE_PORTS.includes(p));
    if (down.length !== STORE_PORTS.length || ports.filter((p) => portDefs[p]?.family === 'data').length !== STORE_PORTS.length) error(`${at}: store has exactly four ports downward, ${STORE_PORTS.join(', ')}`);
  }
  if (a.name === 'exporter' && !ports.includes('destination')) error(`${at}: exporter has a destination port`);
  if (a.name === 'key' && !ports.includes('key-store')) error(`${at}: key has the key-store port`);
  if (a.family === 'keys' && a.name !== 'key') error(`${at}: the keys family is key`);
  if (a.family === 'data' && !['store', 'exporter'].includes(a.name)) error(`${at}: the data family is store and exporter`);
  if (!isStrList(a.calls)) error(`${at}: calls must be a list of actors ([] for none)`);
}
// calls resolve after every actor is known
for (const a of [...actors, ...platform]) {
  if (!isStrList(a?.calls)) continue;
  for (const c of a.calls) {
    const t = byName.get(c);
    if (c === MACRO) { if (![...byName.values()].some(isAdapter)) error(`${REGISTRY}: ${a.name}: calls ${MACRO}, and there is no adapter`); continue; }
    if (!t) error(`${REGISTRY}: ${a.name}: calls ${c}, which is not an actor`);
    else if (c === a.name) error(`${REGISTRY}: ${a.name}: calls itself`);
    else if (['store', 'key', 'exporter'].includes(c)) error(`${REGISTRY}: ${a.name}: calls ${c}; the data, keys and audit-emit ports reach it, so it is not listed in calls`);
    else if (!['work', 'audit'].includes(t.family)) error(`${REGISTRY}: ${a.name}: calls ${c}, which is in the ${t.family} family; calls go to work and audit actors`);
  }
}
for (const [i, a] of platform.entries()) {
  const at = `${REGISTRY}: platform[${i}]${a?.name ? ` (${a.name})` : ''}`;
  if (!isObj(a)) { error(`${at}: not an object`); continue; }
  if ('family' in a) error(`${at}: a platform piece is not an actor of a family`);
  if (common(a, at, PLATFORM_FIELDS, PLATFORM_REQUIRED) && typeof a.binary !== 'string') error(`${at}: binary must be a string`);
}
for (const e of Object.keys(egressDefs)) if (!usedEgress.has(e)) error(`${REGISTRY}: egress class ${e} is declared and no actor uses it`);
const holders = actors.filter((a) => a.holder === true).map((a) => a.name).sort();
if (holders.join() !== ['exporter', 'indexer', 'key', 'reader', 'store', 'witness', 'writer'].join()) error(`${REGISTRY}: the credential holders are exactly store, exporter, key, writer, witness, indexer and reader; found ${holders.join(', ')}`);
for (const n of ['store', 'exporter', 'key', 'writer', 'witness', 'indexer', 'reader', 'entry', 'console', 'session', 'exchange', 'policy', 'signer', 'ca', 'ssh-ca', 'quota']) {
  if (!byName.has(n)) error(`${REGISTRY}: the actor ${n} is missing`);
}
const notActors = isObj(reg.not_actors) ? reg.not_actors : {};
for (const n of Object.keys(notActors)) if (everyone.has(n)) error(`${REGISTRY}: ${n} is both an actor and in not_actors`);

// ---- the requirements vocabulary
const index = load('docs/requirements/index.yaml');
const areas = index?.catalogue?.areas ?? {};
const standardsFile = load('docs/requirements/standards.yaml');
const standards = new Map((standardsFile?.standards ?? []).map((s) => [s.id, s]));
for (const a of everyone.values()) {
  for (const c of a.requirement_areas ?? []) if (!(c in areas)) error(`${REGISTRY}: ${a.name}: requirement area ${c} is not declared in docs/requirements/index.yaml`);
  for (const s of a.standards ?? []) if (!standards.has(s)) error(`${REGISTRY}: ${a.name}: standard ${s} is not in docs/requirements/standards.yaml`);
}

// ---- the explorer
const arch = load(EXPLORER);
if (!arch) error(`${EXPLORER} is missing`);
else {
  for (const r of Object.keys(arch.roles ?? {})) if (!byName.has(r)) error(`${EXPLORER}: role ${r} is not an actor of the registry`);
  const node = platform.find((p) => p.name === 'sluis-node');
  if (!node) error(`${REGISTRY}: the node agent sluis-node is missing from platform`);
  else if (arch.node_agent?.title !== 'sluis-node' || arch.node_agent?.binary !== node.binary) error(`${EXPLORER}: node_agent must be sluis-node with the binary ${node.binary}`);
}

// ---- the decision records
const adrDir = join(root, 'docs', 'decisions');
const adrFiles = existsSync(adrDir) ? readdirSync(adrDir).filter((f) => /^[0-9]{4}-.*\.md$/.test(f) && !f.startsWith('0000')) : [];
const adr = new Map(adrFiles.map((f) => [f.slice(0, 4), { file: f, slug: f.replace(/\.md$/, ''), text: readFileSync(join(adrDir, f), 'utf8') }]));
// A record names an actor by its name in backticks (`name`, `name@`, or `name@boundary`) or by an aka phrase;
// the audit pieces, quota and the adapters are also named in plain prose.
const prose = (a) => ['audit'].includes(a.family) || a.name === 'quota' || isAdapter(a);
function names(text, a) {
  if (text.includes(`\`${a.name}\``) || text.includes(`\`${a.name}@`)) return true;
  const words = [...(a.aka ?? []), ...(prose(a) ? [a.name] : [])];
  return words.some((w) => new RegExp(`(?<![\\w-])${esc(w)}(?![\\w-])`, 'i').test(text));
}
for (const a of everyone.values()) {
  const silent = [];
  for (const n of a.adrs ?? []) {
    if (!adr.has(n)) error(`${REGISTRY}: ${a.name}: ADR ${n} is not a record in docs/decisions/`);
    else if (!names(adr.get(n).text, a)) silent.push(n);
  }
  if (silent.length) adrProblem(`${REGISTRY}: ${a.name}: ADR ${silent.join(', ')} ${silent.length === 1 ? 'does' : 'do'} not name the actor`);
}
for (const [n, { text }] of adr) {
  for (const m of text.matchAll(/`([a-z][a-z0-9-]*)@[^`\s]+`/g)) {
    const name = m[1];
    if (name.startsWith('sluis-')) continue; // a unit or a service name, such as sluis-ca@prod.service
    if (!everyone.has(name) && !Object.hasOwn(notActors, name)) {
      adrProblem(`ADR ${n}: the instance name \`${m[0].slice(1, -1)}\` names ${name}, which is not an actor or a declared non-actor of ${REGISTRY}`);
    }
  }
}
const lang = [...adr.values()].find((r) => r.slug.endsWith('-the-language-follows-the-executable'));
const langRecord = lang;
if (!lang) adrProblem('docs/decisions/: the language record (the language follows the executable) is missing');
else {
  const table = /### Per-actor table\n([\s\S]*?)\n\n(?!\|)/.exec(lang.text)?.[1] ?? '';
  const rows = table.split('\n').filter((l) => /^\|/.test(l) && !/^\|[-| ]+\|$/.test(l)).slice(1)
    .map((l) => l.slice(1, -1).split(' | ').map((c) => c.trim()));
  if (!rows.length) adrProblem(`${lang.slug}: no rows under "### Per-actor table"`);
  else for (const a of actors) {
    const keys = a.language_row ? [a.language_row] : [`\`${a.name}\``, `\`${a.name}@\``];
    const hit = rows.filter((r) => keys.some((k) => (a.language_row ? r[0] === k : r[0].includes(k))));
    if (hit.length !== 1) { adrProblem(`${lang.slug}: ${hit.length} rows of the per-actor table name ${keys[0]}, expected 1 (${a.name})`); continue; }
    const [, l = '', rule = ''] = hit[0];
    if (!new RegExp(`\\b${a.language}\\b`).test(l)) adrProblem(`${REGISTRY}: ${a.name}: language ${a.language}, but the language record says "${l}"`);
    if (!new RegExp(`\\b${a.language_rule}\\b`).test(rule)) adrProblem(`${REGISTRY}: ${a.name}: rule ${a.language_rule}, but the language record gives "${rule}"`);
  }
}

// ---- the requirement records
let annotated = 0;
for (const { file, code } of Object.entries(areas).map(([code, v]) => ({ code, file: v.file }))) {
  const doc = load(`docs/requirements/${file}`);
  for (const r of doc?.requirements ?? []) {
    if (!('actors' in r)) continue;
    annotated++;
    if (!isStrList(r.actors) || !r.actors.length) { error(`docs/requirements/${file}: ${r.id}: actors must be a list of actor names`); continue; }
    for (const n of r.actors) {
      const a = everyone.get(n);
      if (!a) error(`docs/requirements/${file}: ${r.id}: ${n} is not an actor of ${REGISTRY}`);
      else if (!(a.requirement_areas ?? []).includes(code)) error(`docs/requirements/${file}: ${r.id}: area ${code} is not a requirement area of ${n} in ${REGISTRY}`);
    }
  }
}

// ---- the generated page
const code = (s) => `\`${s}\``;
const list = (xs, none = 'none', sep = ', ') => (xs.length ? xs.join(sep) : none);
const scopeText = { 'per-boundary': 'one per boundary', front: 'in the front installation', 'per-node': 'one per node', 'per-tenant': 'one per vendor tenant and credential', 'beside-sluis': 'beside sluis, or on its own' };
const adrLink = (n) => (adr.has(n) ? `[ADR ${n}](/decisions/${adr.get(n).slug}/)` : `ADR ${n}`);
const issueLink = (n) => `[#${n}](https://github.com/truvity/sluis/issues/${n})`;
const callText = (c) => (c === MACRO ? 'any adapter' : code(c));

function section(a) {
  const out = ['', `### ${code(a.name)}`, '', a.purpose, ''];
  if (a.family) out.push(`- **Family:** ${a.family}${a.holder ? `; a credential holder: ${a.holds.join('; ')}` : '; holds no credential at rest'}.`);
  else out.push('- **Family:** none; a platform piece, not an actor of a family.');
  if (a.contracts) out.push(`- **Contracts:** ${list(a.contracts.map(code))}.`);
  out.push(`- **Language:** ${a.language}, rule ${a.language_rule} of the ${langRecord ? `[language record](/decisions/${langRecord.slug}/)` : 'language record'}.${a.language_note ? ` ${a.language_note}` : ''}`);
  out.push(`- **Placement:** ${scopeText[a.placement.scope]}; ${a.placement.instances === 'exactly-1' ? 'exactly one instance' : 'any number of instances'}; on ${a.placement.runtimes.join(', ')}.${a.placement.note ? ` ${a.placement.note}` : ''}`);
  out.push(`- **Ports:** ${list(a.ports.map(code))}.`);
  out.push(`- **Calls:** ${list(a.calls.map(callText))}.`);
  out.push(`- **Egress:** ${list(a.egress.map(code))}.`);
  out.push(`- **Key purposes:** ${list(a.key_purposes.map((k) => `${code(k.purpose)} (${k.ops.join(', ')})`))}.`);
  out.push(`- **Decisions:** ${list(a.adrs.map(adrLink))}.`);
  out.push(`- **Requirement areas:** ${list(a.requirement_areas.map((c) => `[${c}](/requirements/${c.toLowerCase()}/)`))}.`);
  out.push(`- **Standards:** ${list(a.standards.map((s) => `${s} ${standards.get(s)?.name ?? ''}`.trim()), 'none', '; ')}.`);
  out.push(`- **Issues:** ${list(a.issues.map(issueLink))}; label ${code(a.label)}.`);
  return out;
}
function render() {
  const out = [BEGIN, ''];
  out.push('| Actor | Family | Holder | Language | Runs | Label |', '|---|---|---|---|---|---|');
  for (const a of [...actors, ...platform]) {
    out.push(`| [${code(a.name)}](#${a.name}) | ${a.family ?? 'platform'} | ${a.holder ? 'yes' : 'no'} | ${a.language} (${a.language_rule}) | ${scopeText[a.placement.scope]}${a.placement.instances === 'exactly-1' ? ', exactly 1' : ''} | ${code(a.label)} |`);
  }
  for (const a of [...actors, ...platform]) out.push(...section(a));
  out.push('', END);
  return out.join('\n');
}
if (existsSync(join(root, PAGE))) {
  const page = read(PAGE);
  const b = page.indexOf(BEGIN);
  const e = page.indexOf(END);
  if (b < 0 || e < b) error(`${PAGE}: the generated block markers are missing`);
  else if (!errors.length) {
    const want = render();
    const have = page.slice(b, e + END.length);
    if (have !== want) {
      if (write) {
        writeFileSync(join(root, PAGE), page.slice(0, b) + want + page.slice(e + END.length));
        console.log(`check-actors: rewrote the generated block of ${PAGE}`);
      } else error(`${PAGE}: the generated block is stale; run \`just actors-write\``);
    }
  }
} else error(`${PAGE} is missing`);

for (const w of warnings) console.warn(`warning: ${w}`);
if (warnings.length) console.warn(`check-actors: ${warnings.length} warnings about the decision records, which are rewritten wave by wave; --strict-adrs makes them errors`);
console.log(`check-actors: ${annotated} requirement records name actors`);
finish(actors.length, 'actors');

